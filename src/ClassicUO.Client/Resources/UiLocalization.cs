        public static bool RequiresUnicode(string text)
        {
            if (text == null) return false;
            foreach (char character in text) if (character > 0xFF) return true;
            return false;
        }

        public static string Translate(string text)
        {
            if (!IsChinese || string.IsNullOrEmpty(text)) return text;
            return Chinese.TryGetValue(text, out string translated) ? translated : text;
        }

        public static string Html(string text)
        {
            if (!IsChinese || string.IsNullOrEmpty(text)) return text;
            return Regex.Replace(text, @"(?<=>)[^<>]+(?=<)|^[^<>]+(?=<)|(?<=>)[^<>]+$|^[^<>]+$", match =>
            {
                string value = match.Value;
                string trimmed = value.Trim();
                string translated = Translate(trimmed);
                int offset = value.IndexOf(trimmed, StringComparison.Ordinal);
                return trimmed.Length == 0 || translated == trimmed ? value : value.Substring(0, offset) + translated + value.Substring(offset + trimmed.Length);
            });
        }

