        public static string PaperdollTitle(string text)
        {
            if (!IsChinese || string.IsNullOrEmpty(text)) return text;
            // ModernUO appends vendor titles with a space; player skill titles use a comma.
            int npcSeparator = text.LastIndexOf(" the ", StringComparison.OrdinalIgnoreCase);
            if (npcSeparator > 0 && NpcTitles.TryGetValue(text.Substring(npcSeparator + 1), out string npcTitle))
                return text.Substring(0, npcSeparator).TrimEnd(',') + "，" + npcTitle;
            int separator = text.LastIndexOf(", ", StringComparison.Ordinal);
            if (separator < 0) return text;
            string suffix = text.Substring(separator + 2);
            if (NpcTitles.TryGetValue(suffix, out string profession))
                return text.Substring(0, separator) + "，" + profession;
            foreach (var rank in Ranks)
            {
                string prefix = rank.Key + " ";
                if (suffix.StartsWith(prefix, StringComparison.Ordinal) &&
                    SkillTitles.TryGetValue(suffix.Substring(prefix.Length), out string title))
                    return text.Substring(0, separator) + "，" + rank.Value + title;
            }
            return text;
        }

